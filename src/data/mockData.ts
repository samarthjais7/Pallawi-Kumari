function getCachedProfileField<K extends keyof typeof INITIAL_COLLEGE_PROFILE>(field: K): typeof INITIAL_COLLEGE_PROFILE[K] {
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      const cached = localStorage.getItem('college_profile');
      if (cached) {
        const parsed = JSON.parse(cached);
        if (parsed && typeof parsed === 'object' && parsed[field] !== undefined && parsed[field] !== null) {
          return parsed[field];
        }
      }
    }
  } catch {
    // empty
  }
  return INITIAL_COLLEGE_PROFILE[field];
}

